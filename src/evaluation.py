def calculate_metrics(
    df: pd.DataFrame,
    env: Any,
    agent: Any,
) -> Dict[str, Any]:
    """
    Calculate summary performance metrics from simulation trajectory.

    Args:
        df: Simulation DataFrame generated by run_simulation.
        env: The AdvertisementEnvironment instance.
        agent: The bandit agent instance.

    Returns:
        Dict[str, Any]: Comprehensive metric summary dictionary.
    """
    total_rounds = len(df)
    total_reward = int(df["reward"].sum())
    average_reward = float(total_reward / total_rounds) if total_rounds > 0 else 0.0

    true_ctrs = env.get_true_ctrs() if hasattr(env, "get_true_ctrs") else getattr(env, "current_ctrs", None)
    best_ad_idx, best_ad_name, max_true_ctr = env.get_best_ad() if hasattr(env, "get_best_ad") else (0, "Ad 1", 0.0)

    selection_counts = agent.get_selection_counts() if hasattr(agent, "get_selection_counts") else agent.counts
    selection_percentages = (selection_counts / total_rounds) * 100.0 if total_rounds > 0 else np.zeros_like(selection_counts)
    estimated_ctrs = agent.get_estimated_ctrs() if hasattr(agent, "get_estimated_ctrs") else np.zeros(env.num_ads)
    ad_rewards = agent.total_rewards.astype(int)

    # Agent's most frequently selected ad
    agent_favorite_idx = int(np.argmax(selection_counts))
    agent_favorite_name = env.ad_names[agent_favorite_idx]

    # Final regret metrics
    total_expected_regret = float(df["cumulative_expected_regret"].iloc[-1]) if "cumulative_expected_regret" in df else 0.0
    total_actual_regret = float(df["cumulative_regret"].iloc[-1]) if "cumulative_regret" in df else 0.0

    # Per-ad detailed summary table
    ad_stats = []
    for i in range(env.num_ads):
        true_val = float(true_ctrs[i]) if true_ctrs is not None else 0.0
        est_val = float(estimated_ctrs[i]) if i < len(estimated_ctrs) else 0.0
        ad_stats.append({
            "Advertisement": env.ad_names[i],
            "True CTR": true_val,
            "Estimated CTR": est_val,
            "Absolute Error": float(abs(est_val - true_val)),
            "Selections": int(selection_counts[i]),
            "Selection %": float(round(selection_percentages[i], 2)),
            "Total Clicks": int(ad_rewards[i]),
        })
    ad_summary_df = pd.DataFrame(ad_stats)

    return {
        "total_rounds": total_rounds,
        "total_reward": total_reward,
        "average_reward": average_reward,
        "total_expected_regret": total_expected_regret,
        "total_actual_regret": total_actual_regret,
        "best_ad_index": best_ad_idx,
        "best_ad_name": best_ad_name,
        "max_true_ctr": max_true_ctr,
        "agent_favorite_index": agent_favorite_idx,
        "agent_favorite_name": agent_favorite_name,
        "selection_counts": selection_counts,
        "selection_percentages": selection_percentages,
        "estimated_ctrs": estimated_ctrs,
        "true_ctrs": true_ctrs,
        "ad_summary_df": ad_summary_df,
    }


def generate_plots(
    df: pd.DataFrame,
    env: Any,
    agent: Any,
    save_dir: str = "results",
) -> Dict[str, str]:
    """
    Generate and save standard single-agent evaluation plots for UCB1.
    """
    os.makedirs(save_dir, exist_ok=True)
    saved_paths: Dict[str, str] = {}

    rounds = df["round"].values
    true_ctrs = env.get_true_ctrs()
    estimated_ctrs = agent.get_estimated_ctrs()
    counts = agent.get_selection_counts()
    ad_names = env.ad_names
    num_ads = env.num_ads

    # 1. Cumulative Reward
    fig, ax = plt.subplots(figsize=(8, 5))
    ax.plot(rounds, df["cumulative_reward"].values, color="#1f77b4", linewidth=2, label="UCB Cumulative Reward")
    ax.set_title("UCB Cumulative Reward Over Time", fontweight="bold", pad=12)
    ax.set_xlabel("Round (t)")
    ax.set_ylabel("Cumulative Reward (Clicks)")
    ax.grid(True, linestyle="--", alpha=0.6)
    ax.legend(loc="upper left")
    plt.tight_layout()
    p1_path = os.path.join(save_dir, "cumulative_reward.png")
    fig.savefig(p1_path, dpi=300)
    plt.close(fig)
    saved_paths["cumulative_reward"] = p1_path

    # 2. Cumulative Regret
    fig, ax = plt.subplots(figsize=(8, 5))
    ax.plot(rounds, df["cumulative_expected_regret"].values, color="#d62728", linewidth=2, label="Cumulative Expected Regret")
    ax.set_title("UCB Cumulative Regret Over Time", fontweight="bold", pad=12)
    ax.set_xlabel("Round (t)")
    ax.set_ylabel("Cumulative Regret")
    ax.grid(True, linestyle="--", alpha=0.6)
    ax.legend(loc="upper left")
    plt.tight_layout()
    p2_path = os.path.join(save_dir, "cumulative_regret.png")
    fig.savefig(p2_path, dpi=300)
    plt.close(fig)
    saved_paths["cumulative_regret"] = p2_path

    # 3. Ad Selection Frequency
    fig, ax = plt.subplots(figsize=(8, 5))
    colors = ["#2ca02c" if i == np.argmax(true_ctrs) else "#3b82f6" for i in range(num_ads)]
    bars = ax.bar(ad_names, counts, color=colors, edgecolor="black", alpha=0.85, width=0.55)
    for bar, count in zip(bars, counts):
        height = bar.get_height()
        ax.annotate(
            f"{count:,}",
            xy=(bar.get_x() + bar.get_width() / 2, height),
            xytext=(0, 4),
            textcoords="offset points",
            ha="center",
            va="bottom",
            fontsize=9,
            fontweight="bold",
        )
    ax.set_title("Advertisement Selection Frequency", fontweight="bold", pad=12)
    ax.set_xlabel("Advertisement")
    ax.set_ylabel("Number of Selections")
    ax.grid(True, axis="y", linestyle="--", alpha=0.6)
    plt.tight_layout()
    p3_path = os.path.join(save_dir, "ad_selection_frequency.png")
    fig.savefig(p3_path, dpi=300)
    plt.close(fig)
    saved_paths["ad_selection_frequency"] = p3_path

    # 4. Estimated CTR vs True CTR
    fig, ax = plt.subplots(figsize=(9, 5))
    x_indices = np.arange(num_ads)
    width = 0.35
    ax.bar(x_indices - width / 2, true_ctrs, width, label="True CTR (Hidden)", color="#4f46e5", alpha=0.85)
    ax.bar(x_indices + width / 2, estimated_ctrs, width, label="Estimated CTR (UCB)", color="#f59e0b", alpha=0.85)
    ax.set_title("Estimated CTR vs True CTR", fontweight="bold", pad=12)
    ax.set_xlabel("Advertisement")
    ax.set_ylabel("Click-Through Rate (CTR)")
    ax.set_xticks(x_indices)
    ax.set_xticklabels(ad_names)
    ax.legend(loc="upper right")
    ax.grid(True, axis="y", linestyle="--", alpha=0.6)
    plt.tight_layout()
    p4_path = os.path.join(save_dir, "ctr_comparison.png")
    fig.savefig(p4_path, dpi=300)
    plt.close(fig)
    saved_paths["ctr_comparison"] = p4_path

    # 5. Combined Academic Summary Dashboard
    fig, axs = plt.subplots(2, 2, figsize=(14, 10))
    axs[0, 0].plot(rounds, df["cumulative_reward"].values, color="#1f77b4", linewidth=2)
    axs[0, 0].set_title("A. Cumulative Reward Over Time", fontweight="bold")
    axs[0, 0].set_xlabel("Round (t)")
    axs[0, 0].set_ylabel("Cumulative Clicks")
    axs[0, 0].grid(True, linestyle="--", alpha=0.6)

    axs[0, 1].plot(rounds, df["cumulative_expected_regret"].values, color="#d62728", linewidth=2)
    axs[0, 1].set_title("B. Cumulative Expected Regret Over Time", fontweight="bold")
    axs[0, 1].set_xlabel("Round (t)")
    axs[0, 1].set_ylabel("Cumulative Regret")
    axs[0, 1].grid(True, linestyle="--", alpha=0.6)

    axs[1, 0].bar(ad_names, counts, color=colors, edgecolor="black", alpha=0.85, width=0.5)
    axs[1, 0].set_title("C. Advertisement Selection Frequency", fontweight="bold")
    axs[1, 0].set_xlabel("Advertisement")
    axs[1, 0].set_ylabel("Selections")
    axs[1, 0].grid(True, axis="y", linestyle="--", alpha=0.6)

    axs[1, 1].bar(x_indices - width / 2, true_ctrs, width, label="True CTR", color="#4f46e5", alpha=0.85)
    axs[1, 1].bar(x_indices + width / 2, estimated_ctrs, width, label="Estimated CTR", color="#f59e0b", alpha=0.85)
    axs[1, 1].set_title("D. True CTR vs Estimated CTR Convergence", fontweight="bold")
    axs[1, 1].set_xlabel("Advertisement")
    axs[1, 1].set_ylabel("CTR")
    axs[1, 1].set_xticks(x_indices)
    axs[1, 1].set_xticklabels(ad_names)
    axs[1, 1].legend(loc="upper right")
    axs[1, 1].grid(True, axis="y", linestyle="--", alpha=0.6)

    plt.suptitle("UCB Dynamic Advertisement Selection - Performance Summary", fontsize=14, fontweight="bold", y=0.98)
    plt.tight_layout(rect=[0, 0.03, 1, 0.95])
    p5_path = os.path.join(save_dir, "combined_evaluation.png")
    fig.savefig(p5_path, dpi=300)
    plt.close(fig)
    saved_paths["combined_evaluation"] = p5_path

    return saved_paths


def generate_multi_agent_plots(
    results: Dict[str, pd.DataFrame],
    save_dir: str = "results",
) -> Dict[str, str]:
    """
    Generate side-by-side comparative plots for UCB1, Thompson Sampling, Epsilon-Greedy, and Random.
    """
    os.makedirs(save_dir, exist_ok=True)
    saved_paths = {}

    colors = {
        "UCB1": "#1f77b4",
        "Thompson Sampling": "#2ca02c",
        "Epsilon-Greedy (decay)": "#ff7f0e",
        "Epsilon-Greedy (eps=0.1)": "#9467bd",
        "ε-Greedy (decay)": "#ff7f0e",
        "ε-Greedy (ε=0.1)": "#9467bd",
        "Random / Static": "#d62728",
    }

    # 1. Multi-Agent Cumulative Regret
    fig, ax = plt.subplots(figsize=(9, 5.5))
    for name, df in results.items():
        color = colors.get(name, "#333333")
        regret_col = "cumulative_expected_regret" if "cumulative_expected_regret" in df else "cumulative_regret"
        ax.plot(df["round"], df[regret_col], label=name, color=color, linewidth=2.2)

    ax.set_title("Multi-Algorithm Cumulative Regret Benchmark (Logarithmic vs. Linear)", fontweight="bold", pad=12)
    ax.set_xlabel("Simulation Round (t)")
    ax.set_ylabel("Cumulative Expected Regret")
    ax.grid(True, linestyle="--", alpha=0.6)
    ax.legend(loc="upper left", frameon=True)
    plt.tight_layout()
    p_regret = os.path.join(save_dir, "multi_agent_cumulative_regret.png")
    fig.savefig(p_regret, dpi=300)
    plt.close(fig)
    saved_paths["multi_agent_cumulative_regret"] = p_regret

    # 2. Multi-Agent Cumulative Reward (Clicks)
    fig, ax = plt.subplots(figsize=(9, 5.5))
    for name, df in results.items():
        color = colors.get(name, "#333333")
        ax.plot(df["round"], df["cumulative_reward"], label=name, color=color, linewidth=2.2)

    ax.set_title("Multi-Algorithm Cumulative Clicks Harvested Over Time", fontweight="bold", pad=12)
    ax.set_xlabel("Simulation Round (t)")
    ax.set_ylabel("Cumulative Clicks")
    ax.grid(True, linestyle="--", alpha=0.6)
    ax.legend(loc="upper left", frameon=True)
    plt.tight_layout()
    p_reward = os.path.join(save_dir, "multi_agent_cumulative_reward.png")
    fig.savefig(p_reward, dpi=300)
    plt.close(fig)
    saved_paths["multi_agent_cumulative_reward"] = p_reward

    # 3. Comprehensive Multi-Algorithm Benchmark Summary
    fig, axs = plt.subplots(2, 2, figsize=(14, 10))

    # Regret
    for name, df in results.items():
        color = colors.get(name, "#333333")
        reg_col = "cumulative_expected_regret" if "cumulative_expected_regret" in df else "cumulative_regret"
        axs[0, 0].plot(df["round"], df[reg_col], label=name, color=color, linewidth=2)
    axs[0, 0].set_title("A. Cumulative Regret Trajectories", fontweight="bold")
    axs[0, 0].set_xlabel("Round (t)")
    axs[0, 0].set_ylabel("Cumulative Regret")
    axs[0, 0].grid(True, linestyle="--", alpha=0.6)
    axs[0, 0].legend(loc="upper left")

    # Clicks
    for name, df in results.items():
        color = colors.get(name, "#333333")
        axs[0, 1].plot(df["round"], df["cumulative_reward"], label=name, color=color, linewidth=2)
    axs[0, 1].set_title("B. Cumulative Clicks Harvested", fontweight="bold")
    axs[0, 1].set_xlabel("Round (t)")
    axs[0, 1].set_ylabel("Clicks")
    axs[0, 1].grid(True, linestyle="--", alpha=0.6)
    axs[0, 1].legend(loc="upper left")

    # Final Total Clicks Comparison Bar Chart
    names = list(results.keys())
    final_clicks = [int(df["cumulative_reward"].iloc[-1]) for df in results.values()]
    bar_colors = [colors.get(n, "#333333") for n in names]
    bars = axs[1, 0].bar(names, final_clicks, color=bar_colors, alpha=0.85, edgecolor="black")
    for bar in bars:
        axs[1, 0].annotate(
            f"{int(bar.get_height()):,}",
            xy=(bar.get_x() + bar.get_width() / 2, bar.get_height()),
            xytext=(0, 4),
            textcoords="offset points",
            ha="center",
            fontweight="bold",
        )
    axs[1, 0].set_title("C. Total Clicks at Final Round (T=10,000)", fontweight="bold")
    axs[1, 0].set_ylabel("Total Clicks")
    axs[1, 0].grid(True, axis="y", linestyle="--", alpha=0.6)
    axs[1, 0].tick_params(axis="x", rotation=15)

    # Final Regret Deficit Bar Chart
    final_regrets = [float(df["cumulative_expected_regret"].iloc[-1] if "cumulative_expected_regret" in df else df["cumulative_regret"].iloc[-1]) for df in results.values()]
    bars2 = axs[1, 1].bar(names, final_regrets, color=bar_colors, alpha=0.85, edgecolor="black")
    for bar in bars2:
        axs[1, 1].annotate(
            f"{bar.get_height():.1f}",
            xy=(bar.get_x() + bar.get_width() / 2, bar.get_height()),
            xytext=(0, 4),
            textcoords="offset points",
            ha="center",
            fontweight="bold",
        )
    axs[1, 1].set_title("D. Total Cumulative Regret (Lower is Better)", fontweight="bold")
    axs[1, 1].set_ylabel("Cumulative Regret")
    axs[1, 1].grid(True, axis="y", linestyle="--", alpha=0.6)
    axs[1, 1].tick_params(axis="x", rotation=15)

    plt.suptitle("Comparative Evaluation: Multi-Armed Bandit Algorithms", fontsize=14, fontweight="bold", y=0.98)
    plt.tight_layout(rect=[0, 0.03, 1, 0.95])
    p_summary = os.path.join(save_dir, "multi_agent_benchmark_summary.png")
    fig.savefig(p_summary, dpi=300)
    plt.close(fig)
    saved_paths["multi_agent_benchmark_summary"] = p_summary

    return saved_paths


def generate_contextual_plots(
    df_contextual: pd.DataFrame,
    save_dir: str = "results",
) -> Dict[str, str]:
    """Generate plots for LinUCB personalized contextual bandit."""
    os.makedirs(save_dir, exist_ok=True)
    saved = {}

    fig, axs = plt.subplots(1, 2, figsize=(13, 5))

    axs[0].plot(df_contextual["round"], df_contextual["cumulative_regret"], color="#8b5cf6", linewidth=2.2)
    axs[0].set_title("LinUCB Cumulative Contextual Regret", fontweight="bold")
    axs[0].set_xlabel("Round (t)")
    axs[0].set_ylabel("Cumulative Regret")
    axs[0].grid(True, linestyle="--", alpha=0.6)

    # Selection breakdown
    ad_counts = df_contextual["ad_name"].value_counts()
    axs[1].bar(ad_counts.index, ad_counts.values, color="#6366f1", edgecolor="black", alpha=0.85)
    for i, count in enumerate(ad_counts.values):
        axs[1].annotate(
            f"{count:,}",
            xy=(i, count),
            xytext=(0, 4),
            textcoords="offset points",
            ha="center",
            fontweight="bold",
        )
    axs[1].set_title("LinUCB Personalized Ad Allocations", fontweight="bold")
    axs[1].set_ylabel("Impressions")
    axs[1].grid(True, axis="y", linestyle="--", alpha=0.6)
    axs[1].tick_params(axis="x", rotation=15)

    plt.tight_layout()
    p_path = os.path.join(save_dir, "contextual_linucb_evaluation.png")
    fig.savefig(p_path, dpi=300)
    plt.close(fig)
    saved["contextual_linucb_evaluation"] = p_path
    return saved


def generate_non_stationary_plots(
    results: Dict[str, pd.DataFrame],
    change_point: int = 5000,
    save_dir: str = "results",
) -> Dict[str, str]:
    """Generate plots demonstrating D-UCB adapting to non-stationary CTR shifts."""
    os.makedirs(save_dir, exist_ok=True)
    saved = {}

    fig, ax = plt.subplots(figsize=(9, 5))
    colors = {"UCB1 (Stationary)": "#dc2626", "Discounted-UCB (D-UCB)": "#16a34a", "Sliding-Window UCB": "#2563eb"}

    for name, df in results.items():
        color = colors.get(name, "#475569")
        ax.plot(df["round"], df["cumulative_regret"], label=name, color=color, linewidth=2.2)

    ax.axvline(x=change_point, color="#0f172a", linestyle=":", linewidth=2, label=f"Ad Fatigue Shift (t={change_point})")
    ax.set_title("Non-Stationary Regret: Standard UCB1 vs. Adaptive Discounted-UCB", fontweight="bold", pad=12)
    ax.set_xlabel("Round (t)")
    ax.set_ylabel("Cumulative Regret")
    ax.grid(True, linestyle="--", alpha=0.6)
    ax.legend(loc="upper left")
    plt.tight_layout()

    p_path = os.path.join(save_dir, "non_stationary_comparison.png")
    fig.savefig(p_path, dpi=300)
    plt.close(fig)
    saved["non_stationary_comparison"] = p_path
    return saved
